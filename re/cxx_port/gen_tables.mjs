// Mechanically converts MapGenFastSqrt.h + MapGenAtanTable.h into a single
// TS module (packages/core/src/rmg/cxx/mathTables.ts). Run from repo root:
//   node re/cxx_port/gen_tables.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SQRT_H = 'G:/MapGenerator/MapGenerator/MapGenFastSqrt.h';
const ATAN_H = 'G:/MapGenerator/MapGenerator/MapGenAtanTable.h';
const OUT = 'packages/core/src/rmg/cxx/mathTables.ts';

// ---- sqrt table (16384 uint32) ----
const sqrtText = readFileSync(SQRT_H, 'utf8');
const sqrtVals = [];
const sqrtRe = /0x([0-9A-Fa-f]{8})u/g;
let m;
const sqrtBody = sqrtText.slice(sqrtText.indexOf('kTable[16384]'), sqrtText.indexOf('inline float Sqrt'));
while ((m = sqrtRe.exec(sqrtBody)) !== null) sqrtVals.push(parseInt(m[1], 16));
if (sqrtVals.length !== 16384) throw new Error(`sqrt table: expected 16384, got ${sqrtVals.length}`);

// ---- atan table (4097 float32) ----
const atanText = readFileSync(ATAN_H, 'utf8');
const atanBody = atanText.slice(atanText.indexOf('kTable[4097]'), atanText.indexOf('kSaturation'));
const atanVals = [];
const atanRe = /(-?[0-9]+\.[0-9]+(?:[eE][+-]?[0-9]+)?)f/g;
while ((m = atanRe.exec(atanBody)) !== null) atanVals.push(parseFloat(m[1]));
if (atanVals.length !== 4097) throw new Error(`atan table: expected 4097, got ${atanVals.length}`);
// sanity: first/last match the header comments
if (atanVals[0] !== 0) throw new Error('atan[0] != 0');
const f32 = new Float32Array(atanVals);
if (f32[4096] !== Math.fround(1.5607948303222656)) throw new Error('atan[4096] mismatch');

// step + saturation literals from the header tail
const kStep = 0.024413354694843292;
const kSaturation = 1.5707964;

// ---- emit ----
mkdirSync('packages/core/src/rmg/cxx', { recursive: true });
const lines = [];
lines.push('// AUTO-GENERATED by re/cxx_port/gen_tables.mjs from');
lines.push('// G:/MapGenerator MapGenFastSqrt.h + MapGenAtanTable.h - do not edit.');
lines.push('// sqrt: gamemd dword_8650BC (YRMath::sqrt 0x4CAC40) mantissa table.');
lines.push('// atan: gamemd flt_8610B4 (sub_4CADE0) 4097 float32 entries.');
lines.push('');
lines.push('export const SQRT_TABLE = new Uint32Array([');
for (let i = 0; i < sqrtVals.length; i += 8) {
  lines.push('  ' + sqrtVals.slice(i, i + 8).map((v) => '0x' + v.toString(16).padStart(8, '0')).join(', ') + ',');
}
lines.push(']);');
lines.push('');
lines.push('export const ATAN_TABLE = new Float32Array([');
for (let i = 0; i < f32.length; i += 6) {
  lines.push('  ' + Array.from(f32.slice(i, i + 6)).map((v) => String(v)).join(', ') + ',');
}
lines.push(']);');
lines.push('');
lines.push(`export const ATAN_STEP = ${kStep};          // flt_8650B8 (0x3CC7FE84) as double`);
lines.push(`export const ATAN_SATURATION = ${kSaturation};     // 0x3FC90FDB`);
lines.push('');
lines.push('// F2I64 (Game::F2I64 0x7C5F00): truncate toward zero.');
lines.push('export function F2I64(v: number): number {');
lines.push('  return v < 0 ? Math.ceil(v) : Math.floor(v);');
lines.push('}');
lines.push('');
lines.push('// kUnitScale (Random_w scale dbl_7ED898) = 2^-32 * (1 + 2^-32).');
lines.push('export const K_UNIT_SCALE = 2.3283064370807974e-10;');
lines.push('');
lines.push('// YRMath::sqrt (0x4cac40) - bit-exact; returns float32 like the fstp.');
lines.push('export function yrSqrt(a1: number): number {');
lines.push('  if (a1 === 0) return 0;');
lines.push('  if (a1 < 0) a1 = -a1;');
lines.push('  let u = Math.fround(a1);');
lines.push('  let bits = new Uint32Array(new Float32Array([u]).buffer)[0]!;');
lines.push('  let mant = bits & 0x7fffff;');
lines.push('  const e = (bits >>> 23) - 127;');
lines.push('  if (e & 1) mant |= 0x800000;');
lines.push('  bits = (((e >> 1) + 127) << 23) + SQRT_TABLE[mant >>> 10]!;');
lines.push("  return new Float32Array(new Uint32Array([bits]).buffer)[0]!;");
lines.push('}');
lines.push('');
lines.push('// sub_4CADE0 - table atan; index truncates toward zero, saturates at 4097.');
lines.push('export function tableAtan(x: number): number {');
lines.push('  const index = F2I64(Math.abs(x) / ATAN_STEP);');
lines.push('  const v = index >= 4097 ? ATAN_SATURATION : ATAN_TABLE[index]!;');
lines.push('  return x < 0 ? -v : v;');
lines.push('}');
lines.push('');
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: sqrt=${sqrtVals.length} atan=${f32.length}`);
